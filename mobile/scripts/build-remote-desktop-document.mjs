import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import * as esbuild from 'esbuild'

const mobileRoot = path.resolve(import.meta.dirname, '..')
const ENTRY = path.join(
  mobileRoot,
  'src',
  'remote-desktop',
  'document',
  'remote-desktop-document-entry.ts'
)
const OUTPUT = path.join(
  mobileRoot,
  'src',
  'remote-desktop',
  'remote-desktop-document.generated.ts'
)
// noVNC awaits at module top level, so the document is an ES module and needs WebViews that run one.
const TARGET = ['chrome89', 'safari15']

async function main() {
  // The package exports only its entry, so read its manifest by path.
  const manifest = path.join(mobileRoot, 'node_modules', '@novnc', 'novnc', 'package.json')
  const { version } = JSON.parse(await readFile(manifest, 'utf8'))
  const result = await esbuild.build({
    absWorkingDir: mobileRoot,
    entryPoints: [ENTRY],
    bundle: true,
    format: 'esm',
    minify: true,
    platform: 'browser',
    target: TARGET,
    legalComments: 'none',
    write: false,
    logLevel: 'silent'
  })
  const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')
  await writeFile(
    OUTPUT,
    [
      '// Generated by scripts/build-remote-desktop-document.mjs.',
      `// Package: @novnc/novnc@${version}. Do not edit by hand; regenerate via pnpm postinstall.`,
      `export const REMOTE_DESKTOP_DOCUMENT_SCRIPT = ${JSON.stringify(script)}`,
      ''
    ].join('\n')
  )
}

await main()

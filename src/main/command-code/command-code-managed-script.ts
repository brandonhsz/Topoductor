import { posixCurlCommand } from '../agent-hooks/installation/scripts/hook-post-command'
import { TOPO_AGENT_HOOKS_DISABLED_ENV } from '../../shared/agent-hook-listener/transport/agent-hook-suppression-env'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installation/commands/windows-agent-hook-post-command'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines
} from '../agent-hooks/installation/scripts/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      `if "%${TOPO_AGENT_HOOKS_DISABLED_ENV}%"=="1" exit /b 0`,
      'if "%TOPO_AGENT_HOOK_PORT%"=="" if defined TOPO_AGENT_HOOK_ENDPOINT if exist "%TOPO_AGENT_HOOK_ENDPOINT%" call "%TOPO_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%TOPO_AGENT_HOOK_TOKEN%"=="" if not "%TOPO_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\topo-dev\\agent-hooks" for /r "%APPDATA%\\topo-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      // Per-worktree `pnpm dev` profiles live one level down; FOR /R cannot take a FOR variable as its root.
      'if "%TOPO_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\topo-dev-wt" for /d %%P in ("%APPDATA%\\topo-dev-wt\\*") do call :scanEndpointDir "%%~fP\\agent-hooks"',
      'if "%TOPO_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\topo\\agent-hooks" for /r "%APPDATA%\\topo\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':scanEndpointDir',
      'if not "%TOPO_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'if exist "%~1" for /r "%~1" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%TOPO_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set TOPO_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%TOPO_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    `if [ "\${${TOPO_AGENT_HOOKS_DISABLED_ENV}:-}" = 1 ]; then exit 0; fi`,
    ...buildPosixHookSpoolLines('command-code'),
    '__topo_read_ancestor_var() {',
    '  __topo_name="$1"',
    '  __topo_pid="${PPID:-}"',
    '  while [ -n "$__topo_pid" ] && [ "$__topo_pid" != "0" ] && [ "$__topo_pid" != "1" ]; do',
    '    __topo_env=""',
    '    if [ -r "/proc/$__topo_pid/environ" ]; then',
    '      __topo_env=$(tr "\\000" "\\n" < "/proc/$__topo_pid/environ" 2>/dev/null)',
    '    fi',
    '    if [ -z "$__topo_env" ]; then',
    '      __topo_env=$(ps eww -p "$__topo_pid" -o command= 2>/dev/null | tr " " "\\n")',
    '    fi',
    // A scrubbed hook may recover identity, but must never cross a background launch.
    `    if printf '%s\\n' "$__topo_env" | grep -qx '${TOPO_AGENT_HOOKS_DISABLED_ENV}=1'; then return 1; fi`,
    '    __topo_value=$(printf "%s\\n" "$__topo_env" | sed -n "s/^${__topo_name}=//p" | head -n 1)',
    '    if [ -n "$__topo_value" ]; then',
    '      printf "%s\\n" "$__topo_value"',
    '      return 0',
    '    fi',
    '    __topo_pid=$(ps -o ppid= -p "$__topo_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__topo_fill_from_ancestor() {',
    '  __topo_name="$1"',
    '  case "$__topo_name" in',
    '    TOPO_AGENT_HOOK_ENDPOINT) [ -z "${TOPO_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    TOPO_AGENT_HOOK_PORT) [ -z "${TOPO_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    TOPO_AGENT_HOOK_TOKEN) [ -z "${TOPO_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    TOPO_AGENT_HOOK_ENV) [ -z "${TOPO_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    TOPO_AGENT_HOOK_VERSION) [ -z "${TOPO_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    TOPO_PANE_KEY) [ -z "${TOPO_PANE_KEY:-}" ] || return 0 ;;',
    '    TOPO_TAB_ID) [ -z "${TOPO_TAB_ID:-}" ] || return 0 ;;',
    '    TOPO_WORKTREE_ID) [ -z "${TOPO_WORKTREE_ID:-}" ] || return 0 ;;',
    '    TOPO_AGENT_LAUNCH_TOKEN) [ -z "${TOPO_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __topo_value=$(__topo_read_ancestor_var "$__topo_name") || return 0',
    '  [ -n "$__topo_value" ] && export "$__topo_name=$__topo_value"',
    '}',
    '__topo_endpoint_value() {',
    '  __topo_endpoint_name="$1"',
    '  __topo_endpoint_path="$2"',
    '  sed -n "s/^${__topo_endpoint_name}=//p" "$__topo_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__topo_fill_from_endpoint_file() {',
    '  __topo_endpoint_path="$1"',
    '  [ -r "$__topo_endpoint_path" ] || return 0',
    '  __topo_endpoint_port=$(__topo_endpoint_value TOPO_AGENT_HOOK_PORT "$__topo_endpoint_path")',
    '  if [ -n "${TOPO_AGENT_HOOK_PORT:-}" ] && [ -n "$__topo_endpoint_port" ] && [ "$__topo_endpoint_port" != "$TOPO_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __topo_endpoint_name in TOPO_AGENT_HOOK_PORT TOPO_AGENT_HOOK_TOKEN TOPO_AGENT_HOOK_ENV TOPO_AGENT_HOOK_VERSION; do',
    '    eval "__topo_current=\\${$__topo_endpoint_name:-}"',
    '    [ -z "$__topo_current" ] || continue',
    '    __topo_endpoint_value=$(__topo_endpoint_value "$__topo_endpoint_name" "$__topo_endpoint_path")',
    '    [ -n "$__topo_endpoint_value" ] && export "$__topo_endpoint_name=$__topo_endpoint_value"',
    '  done',
    '}',
    '# Recover pane/hook metadata from the parent TUI after Command Code sanitizes hook env.',
    'for __topo_name in TOPO_AGENT_HOOK_ENDPOINT TOPO_AGENT_HOOK_PORT TOPO_AGENT_HOOK_TOKEN TOPO_AGENT_HOOK_ENV TOPO_AGENT_HOOK_VERSION TOPO_PANE_KEY TOPO_TAB_ID TOPO_WORKTREE_ID TOPO_AGENT_LAUNCH_TOKEN; do',
    '  __topo_fill_from_ancestor "$__topo_name"',
    'done',
    'if [ -n "$TOPO_AGENT_HOOK_ENDPOINT" ] && [ -r "$TOPO_AGENT_HOOK_ENDPOINT" ]; then',
    '  __topo_fill_from_endpoint_file "$TOPO_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Recover stripped token metadata by matching the preserved loopback port.',
    'if [ -z "$TOPO_AGENT_HOOK_TOKEN" ] && [ -n "$TOPO_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/topo-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/topo-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/topo-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/topo-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/topo-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/topo-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/topo/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/topo/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^TOPO_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$TOPO_AGENT_HOOK_PORT" ]; then',
    '      __topo_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$TOPO_AGENT_HOOK_PORT" ] || [ -z "$TOPO_AGENT_HOOK_TOKEN" ] || [ -z "$TOPO_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Bound stalled posts and pipe large payloads through stdin to avoid EDR command-line false positives.
    `printf '%s' "$payload" | ${posixCurlCommand()} -sS -X POST "http://127.0.0.1:\${TOPO_AGENT_HOOK_PORT}/hook/command-code" \\`,
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-Topo-Agent-Hook-Token: ${TOPO_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${TOPO_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${TOPO_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${TOPO_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${TOPO_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${TOPO_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${TOPO_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
